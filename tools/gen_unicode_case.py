#!/usr/bin/env python3
"""Generate full Unicode case-mapping data.

Usage:
  python3 tools/gen_unicode_case.py SpecialCasing.txt \
      DerivedCoreProperties.txt src/runtime/data/unicode_case_data.inc

SpecialCasing.txt provides the unconditional (locale-independent) full
lowercase and uppercase mappings, including expansions such as
LATIN SMALL LETTER SHARP S -> "SS".

DerivedCoreProperties.txt provides the `Cased` and `Case_Ignorable` ranges
needed by the Final_Sigma condition of the default lowercase algorithm.
"""

import sys

MAX_MAPPING = 3


def parse_mapping(field):
    text = field.strip()
    if not text:
        return []
    return [int(part, 16) for part in text.split()]


def parse_range(text):
    text = text.strip()
    if ".." in text:
        first, last = text.split("..", 1)
        return int(first, 16), int(last, 16)
    value = int(text, 16)
    return value, value


def merge_ranges(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and merged[-1][1] + 1 == first:
            merged[-1][1] = last
        else:
            merged.append([first, last])
    return merged


def read_special_casing(path):
    entries = {}
    with open(path, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [part.strip() for part in line.split(";")]
            if len(parts) < 4:
                continue
            condition = parts[4] if len(parts) > 4 else ""
            if condition:
                continue
            codepoint = int(parts[0], 16)
            lower = parse_mapping(parts[1])
            upper = parse_mapping(parts[3])
            if lower == [codepoint] and upper == [codepoint]:
                continue
            if len(lower) > MAX_MAPPING or len(upper) > MAX_MAPPING:
                raise SystemExit(
                    f"mapping for U+{codepoint:04X} exceeds {MAX_MAPPING}")
            entries[codepoint] = (lower, upper)
    return entries


def read_properties(path):
    wanted = {"Cased": [], "Case_Ignorable": []}
    with open(path, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [part.strip() for part in line.split(";")]
            if len(parts) < 2 or parts[1] not in wanted:
                continue
            wanted[parts[1]].append(parse_range(parts[0]))
    return {name: merge_ranges(ranges) for name, ranges in wanted.items()}


def padded(values):
    slots = ", ".join(f"0x{value:04X}" for value in values)
    if len(values) < MAX_MAPPING:
        slots += ", 0" * (MAX_MAPPING - len(values))
    return "{" + slots + "}"


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    special_source, property_source, destination = sys.argv[1:4]

    specials = read_special_casing(special_source)
    properties = read_properties(property_source)

    lines = [
        "// Generated by tools/gen_unicode_case.py. Do not edit by hand.",
        "// Sources: SpecialCasing-16.0.0.txt,",
        "// DerivedCoreProperties-16.0.0.txt (Unicode 16.0.0).",
        "",
        "struct UnicodeCasePropertyRange {",
        "    uint32_t first;",
        "    uint32_t last;",
        "};",
        "",
        "struct UnicodeCaseSpecial {",
        "    uint32_t codepoint;",
        "    uint8_t lower_length;",
        "    uint8_t upper_length;",
        "    uint32_t lower[3];",
        "    uint32_t upper[3];",
        "};",
        "",
        "static const UnicodeCaseSpecial UNICODE_CASE_SPECIAL[] = {",
    ]
    for codepoint, (lower, upper) in sorted(specials.items()):
        lines.append(
            f"    {{0x{codepoint:04X}, {len(lower)}, {len(upper)}, "
            f"{padded(lower)}, {padded(upper)}}},")
    lines.append("};")
    lines.append("")

    for name, symbol in (("Cased", "UNICODE_CASE_CASED"),
                         ("Case_Ignorable", "UNICODE_CASE_IGNORABLE")):
        lines.append(f"static const UnicodeCasePropertyRange {symbol}[] = {{")
        for first, last in properties[name]:
            lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
        lines.append("};")
        lines.append("")

    while lines and not lines[-1]:
        lines.pop()
    with open(destination, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
