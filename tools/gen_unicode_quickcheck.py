#!/usr/bin/env python3
"""Generate compact Unicode normalization quick-check ranges.

Usage:
  python3 tools/gen_unicode_quickcheck.py DerivedNormalizationProps.txt \
      src/runtime/data/unicode_quickcheck.inc
"""

import sys


FORMS = ("NFC_QC", "NFD_QC", "NFKC_QC", "NFKD_QC")
VALUES = {"N": 1, "M": 2}


def parse_range(text):
    text = text.strip()
    if ".." in text:
        first, last = text.split("..", 1)
        return int(first, 16), int(last, 16)
    value = int(text, 16)
    return value, value


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source, destination = sys.argv[1], sys.argv[2]
    data = {name: {} for name in FORMS}
    with open(source, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [part.strip() for part in line.split(";")]
            if len(parts) < 3 or parts[1] not in data:
                continue
            value = VALUES.get(parts[2])
            if value is None:
                continue
            first, last = parse_range(parts[0])
            data[parts[1]][(first, last)] = value

    def merged(entries):
        ranges = []
        for (first, last), value in sorted(entries.items()):
            if ranges and ranges[-1][1] + 1 == first and ranges[-1][2] == value:
                ranges[-1][1] = last
            else:
                ranges.append([first, last, value])
        return ranges

    lines = [
        "// Generated by tools/gen_unicode_quickcheck.py. Do not edit by hand.",
        "// Source: DerivedNormalizationProps-16.0.0.txt (Unicode 16.0.0).",
        "",
        "struct UnicodeQuickCheckRange {",
        "    uint32_t first;",
        "    uint32_t last;",
        "    uint8_t value; // 1 = No, 2 = Maybe",
        "};",
        "",
    ]
    for form in FORMS:
        ranges = merged(data[form])
        name = form.replace("_QC", "")
        lines.append(f"static const UnicodeQuickCheckRange {name}_QC_RANGES[] = {{")
        for first, last, value in ranges:
            lines.append(
                f"    {{0x{first:04X}, 0x{last:04X}, {value}}},")
        lines.append("};")
        lines.append("")
    while lines and not lines[-1]:
        lines.pop()
    with open(destination, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
