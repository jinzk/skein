#!/usr/bin/env python3
"""Generate unicode_ident_data.inc for the Skein scanner.

By default this uses Python's Unicode database (str.isidentifier() implements
XID_Start/XID_Continue).  Pass a path to DerivedCoreProperties.txt to generate
from an explicit UCD release instead.

Usage:
    tools/gen_unicode_ident.py > unicode_ident_data.inc
    tools/gen_unicode_ident.py --ucd DerivedCoreProperties.txt \
        > unicode_ident_data.inc
"""

import argparse
import sys
import unicodedata


def merged_ranges(predicate, first, last):
    ranges = []
    start = None
    previous = None
    for cp in range(first, last + 1):
        if predicate(cp):
            if start is None:
                start = cp
            previous = cp
        elif start is not None:
            ranges.append((start, previous))
            start = None
            previous = None
    if start is not None:
        ranges.append((start, previous))
    return ranges


def parse_ucd(path):
    start = []
    cont = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [field.strip() for field in line.split(";")]
            if len(fields) < 2:
                continue
            prop = fields[1]
            if prop not in ("XID_Start", "XID_Continue"):
                continue
            codepoint = fields[0]
            if ".." in codepoint:
                lo, hi = codepoint.split("..", 1)
                lo = int(lo, 16)
                hi = int(hi, 16)
            else:
                lo = hi = int(codepoint, 16)
            (start if prop == "XID_Start" else cont).append((lo, hi))
    return normalize(start), normalize(cont), "UCD"


def normalize(ranges):
    ranges = sorted(ranges)
    out = []
    for lo, hi in ranges:
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def emit(name, ranges, out):
    out.write(f"static const unicode_range {name}[] = {{\n")
    for lo, hi in ranges:
        out.write(f"    {{0x{lo:04X}u, 0x{hi:04X}u}},\n")
    out.write("};\n\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ucd", help="path to DerivedCoreProperties.txt")
    args = parser.parse_args()

    if args.ucd:
        start, cont, version = parse_ucd(args.ucd)
        version = f"{version} (DerivedCoreProperties.txt)"
    else:
        version = unicodedata.unidata_version
        start = merged_ranges(
            lambda cp: chr(cp).isidentifier(), 0x80, 0x10FFFF)
        cont = merged_ranges(
            lambda cp: ("a" + chr(cp)).isidentifier(), 0x80, 0x10FFFF)

    zero = merged_ranges(
        lambda cp: unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf"),
        0x80, 0x10FFFF)
    wide = merged_ranges(
        lambda cp: unicodedata.east_asian_width(chr(cp)) in ("W", "F"),
        0x80, 0x10FFFF)

    out = sys.stdout
    out.write("/* Generated by tools/gen_unicode_ident.py. Do not edit. */\n")
    out.write(f"/* Unicode version: {version}. */\n")
    out.write("#ifndef SKEIN_UNICODE_IDENT_DATA_INC\n")
    out.write("#define SKEIN_UNICODE_IDENT_DATA_INC\n\n")
    emit("kXidStartRanges", start, out)
    emit("kXidContinueRanges", cont, out)
    emit("kZeroWidthRanges", zero, out)
    emit("kWideRanges", wide, out)
    out.write(f'static const char kUnicodeVersion[] = "{version}";\n')
    out.write("\n#endif\n")


if __name__ == "__main__":
    main()
